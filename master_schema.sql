-- (C) Plan Activation Notification & Ledger
CREATE OR REPLACE FUNCTION public.handle_user_plan_activation()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_plan_name text;
  v_referrer_code text;
  v_referrer_id uuid;
  v_bonus numeric;
  v_plan_price numeric;
  v_referred_name text;
  v_is_activation boolean;
BEGIN
  IF TG_OP = 'INSERT' THEN
    v_is_activation := (new.status = 'active' OR new.status = 'approved');
  ELSE
    v_is_activation := (old.status IS DISTINCT FROM 'approved' AND new.status = 'approved') OR (old.status IS DISTINCT FROM 'active' AND new.status = 'active');
  END IF;

  IF v_is_activation THEN
    SELECT 
      COALESCE(name, 'Plan ' || plan_number), 
      COALESCE(plan_price, invest_amount, 0) 
    INTO v_plan_name, v_plan_price 
    FROM public.plans 
    WHERE id = new.plan_id;

    INSERT INTO public.notifications (user_id, title, message, type)
    VALUES (new.user_id, 'Plan Activated! 🎉', 'Congratulations! Your plan "' || COALESCE(v_plan_name, 'Active Plan') || '" is approved. You can now start collecting your daily reward!', 'member_active');

    IF v_plan_price > 0 THEN
      SELECT referred_by, username INTO v_referrer_code, v_referred_name FROM public.profiles WHERE id = new.user_id;
      IF v_referrer_code IS NOT NULL AND TRIM(v_referrer_code) <> '' THEN
        SELECT id INTO v_referrer_id FROM public.profiles WHERE referral_code = TRIM(v_referrer_code);
        IF v_referrer_id IS NOT NULL THEN
          BEGIN
            SELECT CAST(COALESCE(NULLIF(setting_value, ''), '50') AS numeric) INTO v_bonus FROM public.app_settings WHERE setting_key = 'referral_bonus';
          EXCEPTION WHEN OTHERS THEN
            v_bonus := 50;
          END;
          IF v_bonus IS NULL THEN v_bonus := 50; END IF;

          INSERT INTO public.referral_collections (referrer_id, referred_user_id, amount) 
          VALUES (v_referrer_id, new.user_id, v_bonus)
          ON CONFLICT DO NOTHING;

          INSERT INTO public.notifications (user_id, title, message, type)
          VALUES (v_referrer_id, 'Referral Tracked! 🤝', 'Your team member (' || COALESCE(v_referred_name, 'Someone') || ') activated their account! This counts towards your Salary Levels.', 'referral_bonus');
        END IF;
      END IF;
    END IF;
  END IF;
  RETURN new;
END;
$$;

DROP TRIGGER IF EXISTS on_user_plan_activation ON public.user_plans CASCADE;
CREATE TRIGGER on_user_plan_activation
  AFTER INSERT OR UPDATE ON public.user_plans
  FOR EACH ROW EXECUTE FUNCTION public.handle_user_plan_activation();

