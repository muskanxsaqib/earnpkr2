-- (A) Atomic Row-Locking Balance Deduction (Anti-Double-Spend)
CREATE OR REPLACE FUNCTION public.atomic_deduct_balance(
    p_user_id UUID,
    p_amount NUMERIC
)
RETURNS NUMERIC
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_current_balance NUMERIC;
    v_new_balance NUMERIC;
BEGIN
    IF p_amount <= 0 THEN
        RAISE EXCEPTION 'Deduction amount must be strictly positive';
    END IF;

    SELECT balance INTO v_current_balance
    FROM public.profiles
    WHERE id = p_user_id
    FOR UPDATE;

    IF v_current_balance IS NULL THEN
        RAISE EXCEPTION 'User profile not found';
    END IF;

    IF v_current_balance < p_amount THEN
        RAISE EXCEPTION 'Insufficient balance: available %, requested %', v_current_balance, p_amount;
    END IF;

    v_new_balance := v_current_balance - p_amount;

    UPDATE public.profiles
    SET balance = v_new_balance
    WHERE id = p_user_id;

    RETURN v_new_balance;
END;
$$;

-- (B) Atomic Balance Credit
CREATE OR REPLACE FUNCTION public.atomic_credit_balance(
    p_user_id UUID,
    p_amount NUMERIC
)
RETURNS NUMERIC
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_new_balance NUMERIC;
BEGIN
