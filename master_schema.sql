        RAISE EXCEPTION 'Credit amount must be strictly positive';
    END IF;

    UPDATE public.profiles
    SET balance = balance + p_amount
    WHERE id = p_user_id
    RETURNING balance INTO v_new_balance;

    RETURN v_new_balance;
END;
$$;

-- (C) Secure Daily Reward Claiming
CREATE OR REPLACE FUNCTION public.secure_claim_daily_reward(
  p_user_plan_id uuid,
  p_day_number int
)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
  v_user_id uuid;
  v_plan_id bigint;
  v_plan_status text;
  v_start_date timestamp with time zone;
  v_daily_reward numeric;
  v_members_required int;
  v_free_days int := 1;
  v_free_setting text;
  v_now timestamp with time zone := now();
  v_available_at timestamp with time zone;
  v_active_ref_count int := 0;
  v_referral_code text;
  v_existing_status text;
  v_current_balance numeric;
  v_new_balance numeric;
BEGIN
  v_user_id := auth.uid();
  IF v_user_id IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'error', 'Authentication required.');
  END IF;

  IF p_day_number < 1 OR p_day_number > 30 THEN
    RETURN jsonb_build_object('ok', false, 'error', 'Invalid day number (1-30).');
  END IF;

  SELECT up.plan_id, up.status, up.start_date, p.daily_reward, p.members_required
  INTO v_plan_id, v_plan_status, v_start_date, v_daily_reward, v_members_required
  FROM public.user_plans up
  JOIN public.plans p ON p.id = up.plan_id
  WHERE up.id = p_user_plan_id AND up.user_id = v_user_id;

  IF v_plan_id IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'error', 'Active plan not found.');
  END IF;

  IF v_plan_status != 'active' THEN
    RETURN jsonb_build_object('ok', false, 'error', 'This plan is not currently active.');
  END IF;

  v_available_at := COALESCE(v_start_date, v_now) + ((p_day_number - 1) * interval '24 hours');
  IF v_now < v_available_at THEN
    RETURN jsonb_build_object('ok', false, 'error', 'Day ' || p_day_number || ' is not yet unlocked. Please wait.');
  END IF;

  SELECT setting_value INTO v_free_setting
  FROM public.app_settings
  WHERE setting_key = 'free_reward_days'
  LIMIT 1;

  IF v_free_setting ~ '^[0-9]+$' THEN
    v_free_days := v_free_setting::int;
  END IF;

  IF p_day_number > v_free_days AND v_members_required > 0 THEN
    SELECT referral_code INTO v_referral_code FROM public.profiles WHERE id = v_user_id;

    SELECT COUNT(DISTINCT prof.id) INTO v_active_ref_count
    FROM public.profiles prof
    JOIN public.user_plans up ON up.user_id = prof.id AND up.status = 'active'
    WHERE prof.referred_by = v_referral_code;

    IF v_active_ref_count < v_members_required THEN
      RETURN jsonb_build_object(
        'ok', false,
        'error', 'Day ' || p_day_number || ' requires ' || v_members_required || ' active referrals. You currently have ' || v_active_ref_count || '.'
      );
    END IF;
  END IF;

  SELECT status INTO v_existing_status
  FROM public.daily_rewards
  WHERE user_plan_id = p_user_plan_id AND day_number = p_day_number;

  IF v_existing_status = 'collected' THEN
    RETURN jsonb_build_object('ok', false, 'error', 'Day ' || p_day_number || ' reward has already been claimed.');
  END IF;

  INSERT INTO public.daily_rewards (user_plan_id, user_id, day_number, reward_amount, status, collected_at, available_at)
  VALUES (p_user_plan_id, v_user_id, p_day_number, v_daily_reward, 'collected', v_now, v_available_at)
  ON CONFLICT (user_plan_id, day_number)
  DO UPDATE SET
    status = 'collected',
    collected_at = v_now,
    reward_amount = v_daily_reward;

  SELECT balance INTO v_current_balance
  FROM public.profiles
  WHERE id = v_user_id
  FOR UPDATE;

  v_new_balance := COALESCE(v_current_balance, 0) + v_daily_reward;

  UPDATE public.profiles
  SET
    balance = v_new_balance,
    total_earnings = COALESCE(total_earnings, 0) + v_daily_reward
  WHERE id = v_user_id;

  RETURN jsonb_build_object(
    'ok', true,
    'message', 'Day ' || p_day_number || ' reward (PKR ' || v_daily_reward || ') collected successfully!',
    'amount', v_daily_reward,
    'day_number', p_day_number,
    'new_balance', v_new_balance
  );
END;
$$;

-- (D) Deposit Approval & Plan Activation Function
CREATE OR REPLACE FUNCTION public.approve_deposit(p_deposit_id uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
  v_user_id uuid;
  v_plan_id bigint;
  v_platform_method_id bigint;
  v_sender_account_name text;
  v_sender_account_number text;
  v_screenshot_url text;
  v_amount numeric;
  v_daily_reward numeric;
  i int;
BEGIN
  UPDATE public.deposits SET status = 'approved', receipt_url = COALESCE(receipt_url, screenshot_url) WHERE id = p_deposit_id;

  SELECT user_id, plan_id, platform_method_id, user_account_name, user_account_number, screenshot_url, amount
  INTO v_user_id, v_plan_id, v_platform_method_id, v_sender_account_name, v_sender_account_number, v_screenshot_url, v_amount
  FROM public.deposits
  WHERE id = p_deposit_id;

  IF v_platform_method_id IS NULL OR NOT EXISTS (SELECT 1 FROM public.payment_methods WHERE id = v_platform_method_id) THEN
    SELECT id INTO v_platform_method_id FROM public.payment_methods WHERE is_active = true LIMIT 1;
    IF v_platform_method_id IS NULL THEN
      SELECT id INTO v_platform_method_id FROM public.payment_methods LIMIT 1;
    END IF;
  END IF;

  IF v_user_id IS NOT NULL THEN
    INSERT INTO public.user_plans (
      id,
      user_id,
      plan_id,
      status,
      admin_payment_method_id,
      sender_account_name,
      sender_account_number,
      receipt_image_url,
      created_at,
      approved_at,
      start_date
    ) VALUES (
      p_deposit_id,
      v_user_id,
      v_plan_id,
      'active',
      COALESCE(v_platform_method_id, 1),
      COALESCE(v_sender_account_name, 'Unknown'),
      COALESCE(v_sender_account_number, 'Unknown'),
      COALESCE(v_screenshot_url, ''),
      now(),
      now(),
      now()
    )
    ON CONFLICT (id) DO UPDATE SET
      status = 'active',
      approved_at = now(),
      start_date = now();

    SELECT COALESCE(daily_reward, daily_return, 0)
    INTO v_daily_reward
    FROM public.plans
    WHERE id = v_plan_id;

    IF v_daily_reward IS NULL OR v_daily_reward = 0 THEN
      v_daily_reward := COALESCE(v_amount, 0) * 0.05;
    END IF;

    FOR i IN 1..COALESCE((SELECT NULLIF(total_days, 0) FROM public.plans WHERE id = v_plan_id), 30) LOOP
      INSERT INTO public.daily_rewards (
        user_plan_id,
        user_id,
        day_number,
        status,
        reward_amount,
        available_at
      ) VALUES (
        p_deposit_id,
        v_user_id,
        i,
        'pending',
        COALESCE(v_daily_reward, 0),
        now() + ((i - 1) || ' days')::interval
      )
      ON CONFLICT (user_plan_id, day_number) DO NOTHING;
    END LOOP;
  END IF;
END;
$$;

-- (E) Withdrawal Request Procedure
CREATE OR REPLACE FUNCTION public.request_withdrawal(
  p_amount numeric,
  p_method text,
  p_account_number text,
  p_account_name text
)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
  v_user_id uuid;
  v_balance numeric;
  v_pending_count int;
  v_min_withdraw numeric := 100;
  v_min_setting text;
  v_withdrawal_id text;
BEGIN
  v_user_id := auth.uid();
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;

  SELECT setting_value INTO v_min_setting
  FROM public.app_settings
  WHERE setting_key IN ('min_withdraw_amount', 'min_withdrawal')
  ORDER BY updated_at DESC NULLS LAST
  LIMIT 1;

  IF v_min_setting IS NOT NULL AND v_min_setting ~ '^[0-9]+(\.[0-9]+)?$' THEN
    v_min_withdraw := v_min_setting::numeric;
  END IF;

  IF p_amount < v_min_withdraw THEN
    RAISE EXCEPTION 'Minimum withdrawal request amount % PKR hai.', v_min_withdraw;
  END IF;

  SELECT COUNT(*) INTO v_pending_count
  FROM public.withdrawals
  WHERE user_id = v_user_id AND status = 'pending';

  IF v_pending_count > 0 THEN
    RAISE EXCEPTION 'You already have an active pending withdrawal request.';
  END IF;

  SELECT balance INTO v_balance
  FROM public.profiles
  WHERE id = v_user_id
  FOR UPDATE;

  IF v_balance IS NULL OR v_balance < p_amount THEN
    RAISE EXCEPTION 'Insufficient balance.';
  END IF;

  UPDATE public.profiles
  SET balance = balance - p_amount
  WHERE id = v_user_id;

  INSERT INTO public.withdrawals (user_id, amount, method, account_number, account_name, status)
  VALUES (v_user_id, p_amount, p_method, p_account_number, p_account_name, 'pending')
  RETURNING id::text INTO v_withdrawal_id;

  RETURN v_withdrawal_id;
END;
$$;

