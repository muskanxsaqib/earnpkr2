-- (G) Withdrawal Rejection and Automatic Refund Procedure
CREATE OR REPLACE FUNCTION public.reject_withdrawal(p_withdrawal_id uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
  v_user_id uuid;
  v_amount numeric;
  v_status text;
BEGIN
  SELECT user_id, amount, status INTO v_user_id, v_amount, v_status 
  FROM public.withdrawals 
  WHERE id = p_withdrawal_id;

  IF v_status = 'pending' THEN
    UPDATE public.profiles SET balance = balance + v_amount WHERE id = v_user_id;
    UPDATE public.withdrawals 
    SET status = 'rejected', 
        rejection_reason = COALESCE(rejection_reason, 'Rejected by admin'),
        processed_at = now(), 
        updated_at = now() 
    WHERE id = p_withdrawal_id;
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.secure_reject_withdrawal(
  p_withdrawal_id uuid,
  p_reason text DEFAULT 'Rejected by admin'
)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
  v_user_id uuid;
  v_amount numeric;
  v_status text;
BEGIN
  SELECT user_id, amount, status INTO v_user_id, v_amount, v_status
  FROM public.withdrawals
  WHERE id = p_withdrawal_id;

  IF v_user_id IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'error', 'Withdrawal record not found.');
  END IF;

  IF v_status != 'pending' THEN
    RETURN jsonb_build_object('ok', false, 'error', 'Withdrawal is not in pending state.');
  END IF;

  UPDATE public.withdrawals
  SET status = 'rejected', rejection_reason = p_reason, processed_at = now(), updated_at = now()
  WHERE id = p_withdrawal_id;

  IF v_amount > 0 THEN
    UPDATE public.profiles
    SET balance = balance + v_amount
    WHERE id = v_user_id;
  END IF;

  RETURN jsonb_build_object('ok', true, 'message', 'Withdrawal rejected and balance refunded.');
END;
$$;

